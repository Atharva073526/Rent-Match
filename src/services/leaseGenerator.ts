import { LeaseAgreement, Property, User } from '../types';

/**
 * Standard Model Tenancy Act aligned draft agreement generator.
 * Explicitly labeled as a legal draft subject to state-specific stamp duty and registration rules.
 */
export function generateDraftLeaseAgreement(
  property: Property,
  tenant: User,
  landlord: User,
  applicationId: string,
  terms: {
    monthlyRent: number;
    securityDeposit: number;
    maintenanceCharges: number;
    durationMonths: number;
    lockInMonths: number;
    noticePeriodMonths: number;
    commencementDate: string;
  }
): LeaseAgreement {
  const leaseId = 'lease_' + Math.random().toString(36).substring(2, 9);
  
  const formattedRent = terms.monthlyRent.toLocaleString('en-IN');
  const formattedDeposit = terms.securityDeposit.toLocaleString('en-IN');
  const formattedMaintenance = terms.maintenanceCharges.toLocaleString('en-IN');

  const agreementText = `
================================================================================
                    RESIDENTIAL LEASE AGREEMENT (DRAFT)
                     MODEL TENANCY ACT COMPLIANT FORMAT
================================================================================

[NOTICE: This document is a standardized draft generated by RentMatch — Mutual Merit
Platform for bilateral review. State registration, e-stamping (e.g. SHCIL / NeSL), 
and verification under applicable state tenancy rules remain mandatory before legal enforcement.]

THIS RESIDENTIAL TENANCY AGREEMENT is executed on this ${new Date().toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' })}

BY AND BETWEEN:

LESSOR / LANDLORD:
Name: ${landlord.name}
Contact Email: ${landlord.email}
Phone: ${landlord.phone || '+91 98XXX XXXXX'}
Verification Status: Verified Landlord (RentMatch Trust Network)
(Hereinafter referred to as the "LESSOR", which expression shall include legal heirs, successors, and assignees)

AND

LESSEE / TENANT:
Name: ${tenant.name}
Contact Email: ${tenant.email}
Phone: ${tenant.phone || '+91 97XXX XXXXX'}
Verification Status: Verified Tenant Profile (RentMatch Trust Network)
(Hereinafter referred to as the "LESSEE", which expression shall include legal heirs, successors, and assignees)

SUBJECT PREMISES:
Property: ${property.title}
Address: ${property.address}, ${property.locality}, ${property.city} - ${property.pincode}
Configuration: ${property.bhk} BHK (${property.furnishing}) | Carpet Area: ${property.carpetAreaSqFt} Sq.Ft.

1. TENANCY TERM & COMMENCEMENT:
   1.1 The tenancy shall commence on ${terms.commencementDate} for a duration of ${terms.durationMonths} months.
   1.2 A minimum Lock-in Period of ${terms.lockInMonths} months shall apply to both parties from commencement.

2. MONTHLY RENT & MAINTENANCE:
   2.1 The LESSEE agrees to pay a monthly rent of ₹${formattedRent}/- (Rupees ${numberToWordsINR(terms.monthlyRent)} only).
   2.2 The monthly rent shall be payable on or before the 5th day of every calendar month.
   2.3 Maintenance charges of ₹${formattedMaintenance}/- shall be payable to the Resident Welfare Association (RWA) / Society.

3. SECURITY DEPOSIT & RENTMATCH ESCROW SAFEGUARD:
   3.1 The LESSEE shall deposit an interest-free refundable Security Deposit of ₹${formattedDeposit}/- (Rupees ${numberToWordsINR(terms.securityDeposit)} only).
   3.2 Deposit Safeguard Clause: Under the RentMatch Escrow protocol, the deposit shall be refunded within 7 banking days of vacating, subject to mutual physical handover inspection and clearance of utility bills.
   3.3 Deductions from the deposit are strictly restricted to verified actual damage beyond fair wear-and-tear and pending utility bills.

4. HOUSE RULES & COMMUNITY LIVING:
   4.1 Dietary & Lifestyle: ${property.rules.dietaryPreference === 'veg_only' ? 'Vegetarian preference observed in apartment' : 'Open dietary preference with mutual consideration'}.
   4.2 Pet Policy: ${property.rules.petsAllowed ? 'Pets permitted with prior notification and responsible handling.' : 'No domestic pets allowed.'}
   4.3 Quiet Hours: Observed between ${property.rules.quietHours}. Both parties respect peaceful co-existence.
   4.4 Remote Work / WFH: ${property.rules.wfhFriendly ? 'Remote work and high-bandwidth home office usage explicitly supported.' : 'Standard residential use.'}

5. NOTICE PERIOD & TERMINATION:
   5.1 Post expiry of the lock-in period, either party may terminate this agreement by providing a written notice of ${terms.noticePeriodMonths} month(s) or equivalent rent in lieu thereof.
   5.2 Arbitrary mid-term rent escalation and abrupt evictions without due cause are explicitly prohibited.

6. SIGNATURES & DISCLOSURE:
   Both parties agree to review these terms transparently through the RentMatch Mutual Merit Platform.
================================================================================
`.trim();

  return {
    id: leaseId,
    applicationId,
    propertyId: property.id,
    propertyTitle: property.title,
    propertyAddress: `${property.address}, ${property.locality}, ${property.city}`,
    tenantId: tenant.id,
    tenantName: tenant.name,
    landlordId: landlord.id,
    landlordName: landlord.name,
    monthlyRent: terms.monthlyRent,
    securityDeposit: terms.securityDeposit,
    maintenanceCharges: terms.maintenanceCharges,
    durationMonths: terms.durationMonths,
    lockInMonths: terms.lockInMonths,
    noticePeriodMonths: terms.noticePeriodMonths,
    commencementDate: terms.commencementDate,
    status: 'draft',
    tenantSignatureStatus: 'pending',
    landlordSignatureStatus: 'pending',
    agreementText,
    escrowStatus: 'not_initiated',
    escrowAmount: terms.securityDeposit,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}

function numberToWordsINR(num: number): string {
  if (num === 0) return 'Zero';
  if (num >= 100000) {
    const lakhs = (num / 100000).toFixed(1);
    return `${lakhs} Lakhs`;
  }
  if (num >= 1000) {
    const thousands = (num / 1000).toFixed(0);
    return `${thousands} Thousand`;
  }
  return num.toString();
}
